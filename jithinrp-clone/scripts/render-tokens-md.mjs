// Renders tokens/tokens.json -> tokens/tokens.md (tables + bullets only). Nothing here is hand-typed data.
import fs from 'node:fs';

const d = JSON.parse(fs.readFileSync('tokens/tokens.json', 'utf8'));
const L = [];
const w = (...a) => L.push(...a);
const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const table = (head, rows) => { w('| ' + head.join(' | ') + ' |', '| ' + head.map(() => '---').join(' | ') + ' |'); rows.forEach((r) => w('| ' + r.map(esc).join(' | ') + ' |')); w(''); };
const merge = (key, sub) => { const m = {}; for (const [p, pd] of Object.entries(d.pages)) for (const [k, v] of Object.entries(sub ? pd[key][sub] : pd[key])) (m[k] = m[k] || { n: 0, pages: [] }), (m[k].n += v), m[k].pages.push(p); return m; };
const sorted = (m) => Object.entries(m).sort((a, b) => b[1].n - a[1].n);
const sheets = d.sheets;
const allRules = Object.entries(sheets).flatMap(([f, s]) => s.rules.map((r) => ({ ...r, file: f.split('/').slice(3).join('/').split('?')[0] })));

w('# Design tokens — jithinrp.com', '', `- Source: live site ${d.source}, computed at ${d.viewport}, pages: ${Object.keys(d.pages).join(', ')}`,
  '- Generated by `scripts/extract-tokens.mjs` + `scripts/render-tokens-md.mjs`; raw data in `tokens.json`',
  '- Counts = number of elements (computed styles) or rules (CSS source) using the value',
  '- Theme: single light theme. No `prefers-color-scheme` media query exists in any stylesheet (see Breakpoints table); body bg = ' + d.pages['/'].bodyBg, '');

// ---------- colors
w('## 1. Colors', '', '### 1.1 CSS variables (:root)', '');
const rootRules = allRules.filter((r) => r.sel === ':root');
table(['File', 'Media', 'Declarations'], rootRules.map((r) => [r.file, r.media || '—', r.css]));
w('### 1.2 Computed colors across all pages (by role)', '');
for (const [role, sub] of [['Text (color)', 'text'], ['Background', 'background'], ['Border', 'border'], ['Outline', 'outline'], ['SVG fill', 'svgFill'], ['SVG stroke', 'svgStroke'], ['Shadow colors', 'shadowColors']]) {
  const m = sorted(merge('colors', sub));
  w(`**${role}** — ${m.length} unique`, '');
  if (m.length) table(['Value', 'Elements', 'Pages'], m.map(([k, v]) => [k, v.n, v.pages.join(' ')]));
  else w('- none found', '');
}
// CSS source literals
const colorRe = /#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|hsla?\([^)]*\)/g;
const lit = {};
for (const r of allRules) {
  for (const decl of r.css.split(/;\s*(?![^(]*\))/)) {
    const [prop, ...rest] = decl.split(':'); const val = rest.join(':');
    for (const c of val.match(colorRe) || []) {
      const role = /^\s*(background|background-color)/.test(prop) ? 'background' : /^\s*color/.test(prop) ? 'text' : /border|outline/.test(prop) ? 'border' : /shadow/.test(prop) ? 'shadow' : /fill|stroke/.test(prop) ? 'svg' : 'other:' + prop.trim();
      const k = c.replace(/\s+/g, ' ').toLowerCase();
      lit[k] = lit[k] || { n: 0, roles: new Set(), files: new Set() };
      lit[k].n++; lit[k].roles.add(role); lit[k].files.add(r.file);
    }
  }
}
w('### 1.3 Color literals in CSS source (all four stylesheets)', '');
table(['Literal', 'Rules', 'Used as', 'Files'], Object.entries(lit).sort((a, b) => b[1].n - a[1].n).map(([k, v]) => [k, v.n, [...v.roles].join(', '), [...v.files].join(', ')]));
// accent: saturated colours
const toRgb = (c) => { let m = c.match(/^#([0-9a-f]{3,8})$/i); if (m) { let h = m[1]; if (h.length < 6) h = [...h].map((x) => x + x).join(''); return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)); } m = c.match(/rgba?\(([^)]*)\)/); if (m) return m[1].split(/[ ,\/]+/).slice(0, 3).map(Number); return null; };
const sat = (rgb) => { const [r, g, b] = rgb; const mx = Math.max(r, g, b), mn = Math.min(r, g, b); return mx === 0 ? 0 : (mx - mn) / mx; };
const accentCandidates = new Set();
for (const k of Object.keys(lit)) { const rgb = toRgb(k); if (rgb && !rgb.some(isNaN) && sat(rgb) > 0.25) accentCandidates.add(k); }
for (const [k] of sorted(merge('colors', 'background'))) { const rgb = toRgb(k); if (rgb && sat(rgb) > 0.25) accentCandidates.add(k); }
w('### 1.4 Accent colors', '', '- Rule used: any color with HSV saturation > 0.25 in the computed or CSS-source lists above (the site has no named accent token)', '- Gradient / WebGL colors also live in HTML `data-colors` attributes (below)', '');
table(['Value'], [...accentCandidates].map((c) => [c]));
w('**`data-colors` attributes on `[data-liquid]` elements (home page, from rendered HTML)**', '');
const home = fs.readFileSync('raw/_rendered/home.html', 'utf8');
const dc = [...home.matchAll(/data-colors="([^"]+)"/g)].map((m) => m[1]);
table(['Palette (WebGL liquid mask)'], [...new Set(dc)].map((x) => [x]));

// ---------- typography
w('## 2. Typography', '', '### 2.1 @font-face', '');
const ff = Object.values(sheets).flatMap((s) => s.fontFaces);
table(['Family', 'File', 'Weight', 'display'], ff.map((t) => [/font-family: ([^;]+)/.exec(t)[1], /url\("([^"]+)"/.exec(t)[1], (/font-weight: ([^;]+)/.exec(t) || [, 'not set'])[1], /font-display: ([^;]+)/.exec(t)[1]]));
w('- All fonts are self-hosted from `/fonts/` on the same origin (no Google Fonts / Typekit link tags). Local copies: `raw/fonts/`', '- Preloaded in `<head>`: Aeonik-Regular, GeistPixel-VF, AwesomeSerifItalic-VF', '');
w('Font load status at 1440 px (document.fonts):', '');
table(['Face / status'], [...new Set(d.pages['/'].fontsLoaded)].map((x) => [x]));
w('Font stacks declared in CSS:', '');
const stacks = {};
allRules.forEach((r) => { const m = /font-family: ([^;]+)/.exec(r.css); if (m) (stacks[m[1]] = stacks[m[1]] || []).push(r.sel); });
table(['font-family', 'Selectors (first 6)'], Object.entries(stacks).map(([k, v]) => [k, v.slice(0, 6).join(', ') + (v.length > 6 ? ` … +${v.length - 6}` : '')]));
w('### 2.2 Type scale (computed, home page, 1440 px)', '');
table(['Element / class', 'Size', 'Weight', 'Line-height', 'Letter-spacing', 'Family', 'Transform', 'Style', 'Sample'], d.pages['/'].typeScale.sort((a, b) => parseFloat(b.fontSize) - parseFloat(a.fontSize)).map((t) => [t.selector, t.fontSize, t.fontWeight, t.lineHeight, t.letterSpacing, t.fontFamily.split(',')[0], t.textTransform, t.fontStyle, t.sample]));
for (const p of Object.keys(d.pages).slice(1)) {
  const rows = d.pages[p].typeScale.sort((a, b) => parseFloat(b.fontSize) - parseFloat(a.fontSize)).slice(0, 25);
  w(`### 2.3 Type scale — ${p} (top 25 by size)`, '');
  table(['Element / class', 'Size', 'Weight', 'Line-height', 'Letter-spacing', 'Family', 'Sample'], rows.map((t) => [t.selector, t.fontSize, t.fontWeight, t.lineHeight, t.letterSpacing, t.fontFamily.split(',')[0], t.sample]));
}

// ---------- spacing / layout
w('## 3. Spacing, layout, shape', '', '### 3.1 Layout variables', '');
w('- `--max: 1340px` content max width; `--gutter: 50px` (32px at ≤1100px); `--band: 100px` vertical rhythm (80px at ≤1100px); `--band-sm: 50px`; `--pad-x: max(var(--gutter), calc((100vw - var(--max)) / 2))`', '- Values copied from `:root` table in 1.1', '');
w('### 3.2 Spacing values in use (computed, all pages, top 25 each)', '');
for (const k of ['padding', 'margin', 'gap']) { const m = sorted(merge('spacing', k)).slice(0, 25); w(`**${k}**`, ''); table(['Value', 'Count'], m.map(([v, x]) => [v, x.n])); }
w('### 3.3 Structural containers on home (1440 px)', '');
table(['Selector', 'Width px', 'max-width', 'display', 'grid-template-columns', 'flex-direction', 'gap', 'padding', 'position'], d.pages['/'].layout.filter((l, i, a) => a.findIndex((x) => x.selector === l.selector) === i).map((l) => [l.selector, l.width, l.maxWidth, l.display, l.gridTemplateColumns || '', l.flexDirection || '', l.gap, l.padding, l.position]));
w('### 3.4 Border radius (computed)', ''); table(['Value', 'Elements'], sorted(merge('radius')).map(([k, v]) => [k, v.n]));
w('### 3.5 Shadows (computed)', ''); table(['box-shadow', 'Elements'], sorted(merge('shadow')).map(([k, v]) => [k, v.n]));
w('### 3.6 Filters / blend modes', ''); table(['Value', 'Elements'], [...sorted(merge('filters')), ...sorted(merge('blend')).map(([k, v]) => ['mix-blend-mode: ' + k, v])].map(([k, v]) => [k, v.n]));
w('### 3.7 z-index (computed values + where declared in CSS source)', '');
const zr = allRules.filter((r) => /z-index: (-?\d+)/.test(r.css)).map((r) => [r.sel, /z-index: (-?\d+)/.exec(r.css)[1], r.file]).sort((a, b) => b[1] - a[1]);
table(['Selector', 'z-index', 'File'], zr);
w('### 3.8 Cursors (computed)', ''); table(['cursor', 'Elements'], sorted(merge('cursors')).map(([k, v]) => [k, v.n]));

// ---------- breakpoints
w('## 4. Breakpoints (@media in source)', '');
const bp = {};
allRules.forEach((r) => { if (r.media) { bp[r.media] = bp[r.media] || { n: 0, files: new Set() }; bp[r.media].n++; bp[r.media].files.add(r.file); } });
table(['Condition', 'Rules inside', 'Files'], Object.entries(bp).map(([k, v]) => [k, v.n, [...v.files].join(', ')]));
w('- Note: the home page shows a `.mobile-gate` ("Hey Mate… open this on a desktop") on small screens; see Components → mobile-gate', '');

// ---------- motion
w('## 5. Motion', '', '### 5.1 @keyframes (CSS)', '');
table(['Name', 'File', 'Definition'], Object.entries(sheets).flatMap(([f, s]) => s.keyframes.map((k) => [k.name, f.split('/').slice(3).join('/').split('?')[0], k.css.replace(/\s+/g, ' ')])));
w('### 5.2 CSS transitions in use (computed, all pages)', '');
table(['property | duration | easing | delay', 'Elements'], sorted(merge('transitions')).map(([k, v]) => [k, v.n]));
w('### 5.3 CSS animations running (computed)', ''); table(['name | duration | easing | iterations | delay', 'Elements'], sorted(merge('animations')).map(([k, v]) => [k, v.n]));
w('### 5.4 CSS rules that declare transition / animation / transform (source)', '');
table(['Selector', 'File', 'Declarations'], allRules.filter((r) => /transition|animation/.test(r.css)).map((r) => [r.sel, r.file, r.css.split(/;\s*/).filter((x) => /transition|animation|will-change/.test(x)).join('; ')]));
w('### 5.5 JS-driven motion (verbatim lines from `site.js?v=170`, `line: code`)', '', '- GSAP, ScrollTrigger, SplitText, Lenis and Three.js are loaded from `/vendor/` (self-hosted)', '- Not interpreted; read the lines to see the actual values', '');
for (const [k, arr] of Object.entries(d.jsMotion)) { w(`**${k}** (${arr.length} lines)`, ''); arr.forEach((l) => w('- `' + l.replace(/`/g, "'") + '`')); w(''); }
w('### 5.6 Behaviour notes (each backed by a source reference above)', '',
  '- Reduced motion: handled in CSS (`prefers-reduced-motion: reduce`, see §4) and in JS (§5.5 `reducedMotion` lines)',
  '- Sound toggle: `<button class="sound-toggle" data-sound-toggle aria-pressed>` in the nav, label "Sound on", keyboard shortcut M (title attr); music file `mp3/Lofi BGM.mp3` (loaded lazily, `preload="none"`); UI sounds use Web Audio API (`AudioContext`, §5.5 `audio`)',
  '- Marquee: `[data-marquee]` track (`.marquee__track` / `.marquee__group`) — speed reacts to scroll speed per HTML comment in source',
  '- Cursor: elements with `data-cursor-pill="…"` show a labelled cursor pill (e.g. "View project", "Download PDF"); §5.5 `cursor`',
  '- WebGL: one shared `<canvas class="liquid-stage">`; elements with `data-liquid` (image/video) are mirrored onto it (HTML comment in source); Three.js',
  '- Video: work cards and AI cards use muted looping `<video preload="none">` with a poster; modals use `preview.mp4` / `trailer.mp4`',
  '- Lottie: **no Lottie player or .json/.lottie animation file is requested by any page** (see `raw/_manifest-pass-b.json`); "Lottiefiles" appears only as an award name',
  '');

// ---------- components
w('## 6. Component inventory', '', '- Each entry: computed summary (1440 px), HTML structure, then the CSS rules whose selector contains the component class', '');
const home_ = d.pages['/'].components;
const prefixes = { nav: ['nav', 'navbar'], 'mobile-gate': ['mobile-gate'], hero: ['hero'], pillar: ['pillar', 'pillars'], marquee: ['marquee'], 'work-card': ['work', 'works', 'fact'], 'ai-project-card': ['ai-card', 'genai', 'track'], 'carousel-arrows': ['arrows', 'arrow'], about: ['about'], 'award-badge': ['award', 'awards'], 'testimonial-card': ['quote', 'quotes', 'track--quotes'], cta: ['contact'], footer: ['footer'], 'project-modal': ['pmodal'], 'sound-toggle': ['sound-toggle'] };
for (const [name, c] of Object.entries(home_)) {
  w(`### 6.${Object.keys(home_).indexOf(name) + 1} ${name} (\`${c.selector}\`)`, '', `- Rendered size: ${c.size}`, "");
  table(['Property', 'Computed value'], Object.entries(c.computed).map(([k, v]) => [k, v]));
  w('**HTML structure**', '', '```html', c.html, '```', '');
  const re = new RegExp('\\.(' + prefixes[name].map((x) => x.replace(/[-]/g, '\\-')).join('|') + ')(?![A-Za-z0-9]|-(?!-)|_(?!_))');
  const rules = allRules.filter((r) => re.test(r.sel));
  w(`**CSS** (${rules.length} rules)`, '', '```css');
  rules.forEach((r) => w(`${r.media ? '/* @media ' + r.media + ' */ ' : ''}${r.sel} { ${r.css} }  /* ${r.file} */`));
  w('```', '');
}
w('## 7. Not extracted / limits', '',
  '- Hover and focus styles: listed through the CSS rules in §6 (`:hover`, `:focus-visible` selectors) — visual proof in `/screenshots/states`',
  '- Values set at runtime by GSAP (inline styles, ScrollTrigger positions) are only visible as the source lines in §5.5; no timeline was replayed',
  '- Shader code for the WebGL liquid effect was not parsed into tokens (see `raw/site.js`)',
  '- Case-study and Memory-game pages: component HTML is not inventoried (task scope = home page components); their CSS rules are included in §1.3, §4, §5', '');
fs.writeFileSync('tokens/tokens.md', L.join('\n'));
console.log('wrote tokens/tokens.md', L.length, 'lines');
